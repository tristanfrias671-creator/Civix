// Server error codes that share one message.
const SAME_MESSAGE = { LIMIT_FILE_SIZE: 'TOO_LARGE', LIMIT_FILE_COUNT: 'FILE_COUNT', LIMIT_UNEXPECTED_FILE: 'FILE_COUNT' };

// The message for a refused report: the server's own words in English; in Filipino
// and Bisaya the translation for its code, or the server's words if there is none.
export function refusalText(t, lang, data, isFeedback) {
  if (lang === 'en' || !data) return data?.error;
  if (data.code === 'DUPLICATE') return isFeedback ? t.errors.duplicateFeedback : t.errors.duplicate(data.trackingId);
  return t.errors[SAME_MESSAGE[data.code] || data.code] || data.error;
}

